#!/usr/bin/env bash
# Prints the Homebrew cask for a release, as published in the GregorLohaus/homebrew-tap repository:
#
#   scripts/homebrew-cask.sh 0.2.0 dist/Wgitpui-0.2.0-macos.zip > Casks/wgitpui.rb
#
# The release workflow runs this for every v* tag and pushes the result to the tap, so edit the
# cask here, not there. REPO is the GitHub repository whose release holds the .zip.
set -euo pipefail

VERSION=${1:?usage: homebrew-cask.sh VERSION ZIP}
ZIP=${2:?usage: homebrew-cask.sh VERSION ZIP}
REPO=${REPO:-GregorLohaus/wgitpui}
SHA256=$(shasum -a 256 "$ZIP" | cut -d' ' -f1)

cat <<CASK
# Generated by scripts/homebrew-cask.sh in $REPO; edit it there.
cask "wgitpui" do
  version "$VERSION"
  sha256 "$SHA256"

  url "https://github.com/$REPO/releases/download/v#{version}/Wgitpui-#{version}-macos.zip"
  name "Wgitpui"
  desc "GPU-rendered git client"
  homepage "https://github.com/$REPO"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on :macos

  app "Wgitpui.app"
  binary "#{appdir}/Wgitpui.app/Contents/MacOS/wgitpui"

  # Release builds are ad-hoc signed, not notarized: with the quarantine flag Homebrew sets,
  # Gatekeeper would block the app and the wgitpui command until approved in System Settings,
  # and again after every upgrade.
  postflight_steps do
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/Wgitpui.app"], must_succeed: false
  end

  zap trash: "~/Library/Application Support/wgitpui"
end
CASK
